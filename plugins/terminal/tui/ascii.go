func asciiOnly(text string) string {
	var out strings.Builder
	out.Grow(len(text))
	for _, r := range text {
		if r < utf8.RuneSelf {
			out.WriteRune(r)
			continue
		}
		out.WriteString(asciiSubstitute(r))
	}
	return out.String()
}

func asciiSubstitute(r rune) string {
	if sub, ok := asciiSubstitutes[r]; ok {
		return sub
	}
	switch {
	case r >= 0x2800 && r <= 0x28ff:
		return "*"
	case r >= 0x2500 && r <= 0x257f:
		return "+"
	case r >= 0x2580 && r <= 0x259f:
		return "#"
	default:
		return "?"
	}
}
