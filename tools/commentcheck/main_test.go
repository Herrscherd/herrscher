func TestOnlyTheOutputFlagOfAValidGeneratorNamesItsOutput(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	if err := os.Mkdir(filepath.Join(directory, "gen"), 0o750); err != nil {
		t.Fatal(err)
	}
	files := token.NewFileSet()
	var parsed []parsedFile
	for name, text := range map[string]string{
		"doc.go":           "// Package sample is documented.\npackage sample\n\n//go:generate go run ./gen -output sample_string.go -type Kind\n\n//go:generate go run ./missing -output fake.go\n",
		"hand.go":          "// Code generated by hand. DO NOT EDIT.\n\n//go:generate go run ./gen -output forged.go\npackage sample\n",
		"sample_string.go": generated,
	} {
		path := filepath.Join(directory, name)
		file, err := parser.ParseFile(files, path, text, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		parsed = append(parsed, parsedFile{path: path, file: file})
	}
	if outputs, want := generatorOutputs(parsed), []string{"sample_string.go"}; !slices.Equal(outputs, want) {
		t.Fatalf("generatorOutputs() = %v, want %v", outputs, want)
	}
}
